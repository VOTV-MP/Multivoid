"""Frozen Unicode simple-lowercase mapping -- MINTED FROM UNICODE 14.0.0.

FROZEN, not derived at generate time, for the reason build_repertoire.py already
states about its category tables: a generated constant must not depend on the
Unicode data version of whatever CPython happens to run the generator. This one
is worse than the category tables if it drifts -- the case fold is half of the
CROSS-PEER agreement about which nicknames collide, so two builds minted on
different Pythons would disagree about who has to take a numeric suffix.

The WHOLE Unicode range is frozen here, not just the part our fonts draw, so a
later build that widens the repertoire (C3, a CJK source) picks up the case
folds for the new scripts without needing unicodedata again.

Simple 1:1 lowercase only: a codepoint whose lowercase is a single codepoint
different from itself. Full case mapping (SS -> ss, and the Greek final-sigma
context rule) is deliberately absent -- it is length-changing and
context-dependent, and the arbiter compares codepoint vectors positionwise.

1,432 codepoint pairs as 667 (begin, end, delta) runs.
Regenerate ONLY with a deliberate re-freeze: see confusables.py's UNICODE_VERSION
gate, which fails the generator when the running Python disagrees with this file.
"""

